CREATE TABLE IF NOT EXISTS pet (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'dog',
  color TEXT NOT NULL DEFAULT '',
  breed TEXT NOT NULL DEFAULT '',
  birth TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  photo INTEGER NOT NULL DEFAULT 0,
  sex TEXT NOT NULL DEFAULT '',
  neutered INTEGER NOT NULL DEFAULT 0,
  chip TEXT NOT NULL DEFAULT '',
  allergies TEXT NOT NULL DEFAULT '',
  food TEXT NOT NULL DEFAULT '',
  portion TEXT NOT NULL DEFAULT '',
  meals TEXT NOT NULL DEFAULT '',
  insurance TEXT NOT NULL DEFAULT '',
  vet_name TEXT NOT NULL DEFAULT '',
  vet_phone TEXT NOT NULL DEFAULT '',
  created TEXT NOT NULL DEFAULT (datetime('now','localtime'))
);

CREATE TABLE IF NOT EXISTS pet_photo (
  pet_id INTEGER PRIMARY KEY REFERENCES pet(id) ON DELETE CASCADE,
  webp BLOB NOT NULL
);

CREATE TABLE IF NOT EXISTS weight (
  id INTEGER PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  kg REAL NOT NULL,
  by INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS weight_pet ON weight(pet_id, day);

CREATE TABLE IF NOT EXISTS med (
  id INTEGER PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  dose TEXT NOT NULL DEFAULT '',
  times TEXT NOT NULL DEFAULT '',
  start TEXT NOT NULL,
  days INTEGER,
  note TEXT NOT NULL DEFAULT '',
  stopped TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS dose (
  med_id INTEGER NOT NULL REFERENCES med(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  slot TEXT NOT NULL,
  by INTEGER NOT NULL DEFAULT 0,
  at TEXT NOT NULL DEFAULT (strftime('%H:%M','now','localtime')),
  PRIMARY KEY (med_id, day, slot)
);

CREATE TABLE IF NOT EXISTS health (
  id INTEGER PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  at TEXT NOT NULL,
  kind TEXT NOT NULL,
  mood TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  by INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS health_pet ON health(pet_id, at);

CREATE TABLE IF NOT EXISTS walk (
  id INTEGER PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  at TEXT NOT NULL,
  minutes INTEGER,
  by INTEGER NOT NULL DEFAULT 0,
  note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS walk_pet ON walk(pet_id, at);

-- Everyone who went on a walk. A walk without rows here was taken by `walk.by` alone.
CREATE TABLE IF NOT EXISTS walk_people (
  walk_id INTEGER NOT NULL REFERENCES walk(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL,
  PRIMARY KEY (walk_id, user_id)
);

CREATE TABLE IF NOT EXISTS visit (
  id INTEGER PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  at TEXT NOT NULL,
  title TEXT NOT NULL,
  place TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  remind INTEGER NOT NULL DEFAULT 1440,
  sent INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS task (
  id INTEGER PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  icon TEXT NOT NULL DEFAULT 'sparkles',
  every INTEGER NOT NULL DEFAULT 0,
  due TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  sent TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS task_done (
  id INTEGER PRIMARY KEY,
  task_id INTEGER NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  by INTEGER NOT NULL DEFAULT 0,
  at TEXT NOT NULL DEFAULT (strftime('%H:%M','now','localtime'))
);

CREATE INDEX IF NOT EXISTS walk_at ON walk(at);
CREATE INDEX IF NOT EXISTS health_at ON health(at);
CREATE INDEX IF NOT EXISTS weight_day ON weight(day);
CREATE INDEX IF NOT EXISTS med_pet ON med(pet_id);
CREATE INDEX IF NOT EXISTS dose_day ON dose(day);
CREATE INDEX IF NOT EXISTS visit_pet ON visit(pet_id, at);
CREATE INDEX IF NOT EXISTS task_pet ON task(pet_id, due);
CREATE INDEX IF NOT EXISTS task_done_task ON task_done(task_id, day);
CREATE INDEX IF NOT EXISTS task_done_day ON task_done(day, at);

CREATE TABLE IF NOT EXISTS setting (
  k TEXT PRIMARY KEY,
  v TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sent (
  k TEXT PRIMARY KEY,
  day TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS fed (
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  slot TEXT NOT NULL,
  by INTEGER NOT NULL DEFAULT 0,
  at TEXT NOT NULL DEFAULT (strftime('%H:%M','now','localtime')),
  PRIMARY KEY (pet_id, day, slot)
);

CREATE TABLE IF NOT EXISTS record (
  id INTEGER PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  kind TEXT NOT NULL DEFAULT 'vaccine',
  name TEXT NOT NULL DEFAULT '',
  day TEXT NOT NULL,
  next TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  sent TEXT NOT NULL DEFAULT ''
);

-- Treats and snacks outside the meal plan: what, how much and who gave it.
CREATE TABLE IF NOT EXISTS treat (
  id INTEGER PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pet(id) ON DELETE CASCADE,
  at TEXT NOT NULL,
  what TEXT NOT NULL,
  amount TEXT NOT NULL DEFAULT '',
  by INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS fed_day ON fed(day, at);
CREATE INDEX IF NOT EXISTS treat_pet ON treat(pet_id, at);
CREATE INDEX IF NOT EXISTS treat_at ON treat(at);
CREATE INDEX IF NOT EXISTS record_pet ON record(pet_id, day);
